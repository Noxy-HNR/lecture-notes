# Data gathering
# ---------------------------------------------------------------------------

def _class_files(code: str) -> dict:
    safe = code.replace(" ", "_")
    return {
        "notes": NOTES_DIR / f"{safe}.md",
        "docx": NOTES_DIR / f"{safe}.docx",
        "study_guide": NOTES_DIR / f"{safe}_study_guide.md",
        "flashcards": NOTES_DIR / f"{safe}_flashcards_anki.txt",
    }


def list_classes() -> list[dict]:
    """Every class that has notes on disk, with enough metadata for the sidebar."""
    if not NOTES_DIR.exists():
        return []
    out = []
    for path in sorted(NOTES_DIR.glob("*.md")):
        if path.stem.endswith("_study_guide"):
            continue
        code = path.stem.replace("_", " ")
        text = path.read_text(encoding="utf-8", errors="replace")
        title_match = re.match(r"^# (.+?)\s*\(", text)
        dates = re.findall(r"^## (.+)$", text, re.MULTILINE)
        files = _class_files(code)
        out.append({
            "code": code,
            "title": title_match.group(1).strip() if title_match else code,
            "lectures": len(dates),
            "latest": dates[-1] if dates else "",
            "words": len(text.split()),
            "updated": path.stat().st_mtime,
            "has_study_guide": files["study_guide"].exists(),
            "has_flashcards": files["flashcards"].exists(),
            "has_docx": files["docx"].exists(),
        })
    return out


def class_document(code: str, kind: str = "notes") -> dict:
    files = _class_files(code)
    path = files.get(kind)
    if not path or not path.exists():
        return {"error": f"no {kind} for {code}"}
    text = path.read_text(encoding="utf-8", errors="replace")
    if kind == "flashcards":
        cards = []
        for line in text.splitlines():
            if line.startswith("#") or "\t" not in line:
                continue
            front, back = line.split("\t", 1)
            cards.append({"front": front, "back": back})
        return {"code": code, "kind": kind, "cards": cards}
    dates = re.findall(r"^## (.+)$", text, re.MULTILINE)
    return {
        "code": code,
        "kind": kind,
        "html": markdown_to_html(text),
        "toc": [{"date": d, "anchor": re.sub(r"[^a-z0-9]+", "-", d.lower()).strip("-")}
                 for d in dates],
        "words": len(text.split()),
        "updated": path.stat().st_mtime,
    }


def list_sessions() -> list[dict]:
    """Recorded sessions from state/, newest first - the raw audio + transcript backups
    behind each lecture."""
    if not STATE_DIR.exists():
        return []
    out = []
    for wav in sorted(STATE_DIR.glob("*.wav"), reverse=True):
        stem = wav.stem
        match = re.match(r"^(.+)_(\d{8})_(\d{6})$", stem)
        if not match:
            continue
        raw = wav.with_name(f"{stem}_raw.txt")
        size = wav.stat().st_size
        out.append({
            "class_code": match.group(1).replace("_", " "),
            "date": f"{match.group(2)[:4]}-{match.group(2)[4:6]}-{match.group(2)[6:]}",
            "time": f"{match.group(3)[:2]}:{match.group(3)[2:4]}",
            "minutes": round(size / (2 * 16000 * 2) / 60, 1),  # float32 mono @16k
            "mb": round(size / 1e6, 1),
            "wav": wav.name,
            "has_transcript": raw.exists(),
            "transcript_lines": len(raw.read_text(encoding="utf-8", errors="replace").splitlines())
                                 if raw.exists() else 0,
        })
    return out


def service_status() -> dict:
    """Point-in-time health of everything the recorder depends on. Imported lazily
    because notes/gpu_formatter pull in the rest of the app, and the dashboard should
    still start (and serve notes) even if one of them is broken."""
    status = {}
    try:
        import notes as notes_module
        status["claude_cli"] = "available" if notes_module.cli_available() else "unavailable"
    except Exception as e:
        status["claude_cli"] = f"error: {type(e).__name__}"
    try:
        import os
        status["claude_api"] = "key set" if os.environ.get("ANTHROPIC_API_KEY") else "no key"
    except Exception:
        status["claude_api"] = "unknown"
    try:
        import gpu_formatter
        if not gpu_formatter.available():
            status["gpu_model"] = "not installed"
        else:
            status["gpu_model"] = "running" if gpu_formatter._server_healthy() else "installed (stopped)"
    except Exception as e:
        status["gpu_model"] = f"error: {type(e).__name__}"
    try:
        import diarize
        status["diarization"] = "enabled" if diarize.available() else "off (no HF token)"
    except Exception as e:
        status["diarization"] = f"error: {type(e).__name__}"
    return status


