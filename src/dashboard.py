"""Local web dashboards for the lecture notes app - a separate process from the recorder.

Two pages, deliberately separate concerns:
  /             Notes    - read, browse and search everything the recorder has produced
  /diagnostics  Live     - what a running session is doing right now, plus the same
                           controls the terminal has (save now / stop)

Runs as its own process so it can never slow down or crash a recording in progress: it
only reads notes/ and state/, and talks to a live recorder through the two small files
in telemetry.py. Starting it while nothing is recording is fine - the notes side works
entirely on its own, and diagnostics just shows the last session's final state.

    python src/dashboard.py [--port 8770] [--no-browser]

Everything is served from this machine with no CDN or external assets, so it works with
no internet - same constraint the rest of the app is built around.
"""
import argparse
import html
import json
import re
import sys
import threading
import time
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

sys.path.insert(0, str(Path(__file__).resolve().parent))

import search as search_module
import telemetry

PROJECT_ROOT = Path(__file__).resolve().parent.parent
NOTES_DIR = PROJECT_ROOT / "notes"
STATE_DIR = PROJECT_ROOT / "state"
STATIC_DIR = PROJECT_ROOT / "dashboard"

DEFAULT_PORT = 8770


# ---------------------------------------------------------------------------
# Markdown rendering
# ---------------------------------------------------------------------------

_BOLD = re.compile(r"\*\*(.+?)\*\*")
_ITALIC = re.compile(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)")


def _inline(text: str) -> str:
    """Escapes first, then re-introduces only the inline formatting we control - notes
    are LLM-generated text, so nothing in them may be trusted as markup."""
    out = html.escape(text)
    out = _BOLD.sub(r"<strong>\1</strong>", out)
    out = _ITALIC.sub(r"<em>\1</em>", out)
    return out


def markdown_to_html(markdown: str) -> str:
    """Handles the limited subset the notes actually use (headings, nested bullets,
    bold/italic). A full markdown library would be a dependency for no benefit - the
    notes are generated by prompts in this repo, so the format is known and bounded."""
    lines_out = []
    list_depth = 0

    def close_lists(to_depth=0):
        nonlocal list_depth
        while list_depth > to_depth:
            lines_out.append("</ul>")
            list_depth -= 1

    for raw in markdown.split("\n"):
        line = raw.rstrip()
        if not line.strip():
            close_lists()
            continue

        bullet = re.match(r"^(\s*)[-*]\s+(.*)$", line)
        if bullet:
            indent = len(bullet.group(1))
            depth = 1 + (indent // 2)
            while list_depth < depth:
                lines_out.append("<ul>")
                list_depth += 1
            close_lists(depth)
            lines_out.append(f"<li>{_inline(bullet.group(2))}</li>")
            continue

        close_lists()
        if line.startswith("### "):
            lines_out.append(f'<h3>{_inline(line[4:].strip())}</h3>')
        elif line.startswith("## "):
            date = line[3:].strip()
            anchor = re.sub(r"[^a-z0-9]+", "-", date.lower()).strip("-")
            lines_out.append(f'<h2 id="{anchor}">{_inline(date)}</h2>')
        elif line.startswith("# "):
            lines_out.append(f"<h1>{_inline(line[2:].strip())}</h1>")
        else:
            lines_out.append(f"<p>{_inline(line)}</p>")

    close_lists()
    return "\n".join(lines_out)


